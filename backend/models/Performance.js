import mongoose from 'mongoose';

const performanceSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      required: true,
      ref: 'User',
    },
    type: {
      type: String,
      required: true,
      enum: ['strength', 'cardio'],
    },
    exerciseName: {
      type: String,
      required: true,
    },
    value: {
      type: Number,
      required: true,
    },
    unit: {
      type: String,
      required: true,
    },
    date: {
      type: Date,
      default: Date.now,
    },
  },
  {
    timestamps: true,
  }
);

performanceSchema.index({ user: 1, exerciseName: 1, date: -1 });
const Performance = mongoose.model('Performance', performanceSchema);

export default Performance;